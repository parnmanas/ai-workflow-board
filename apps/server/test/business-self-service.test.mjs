import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { bootApp, closeTestApp } from './helpers/boot.mjs';
import { createAccount, createUser } from './helpers/fixtures.mjs';
import { assessSelfService, SELF_SERVICE_GUIDES } from '../dist/modules/business/business-self-service.js';

const formationAnswers = Object.fromEntries(SELF_SERVICE_GUIDES.self_formation.questions.map(q => [q.key, q.required_yes]));
const accountingAnswers = Object.fromEntries(SELF_SERVICE_GUIDES.self_bookkeeping.questions.map(q => [q.key, q.required_yes]));
test('DIY conditions keep unknowns unresolved, separate EIN routes and product scope from tax eligibility', () => {
  const company = { country: 'US', entity_type: 'LLC', jurisdiction: 'Delaware' };
  assert.equal(assessSelfService(company, 'self_formation', 'DE').eligible, false);
  assert.equal(assessSelfService(company, 'self_formation', 'DE', formationAnswers).ein_route, 'international');
  assert.equal(assessSelfService(company, 'self_formation', 'DE', { ...formationAnswers, principal_us: true }).ein_route, 'ss4');
  assert.equal(assessSelfService(company, 'self_formation', 'DE', { ...formationAnswers, principal_us: true, responsible_tax_id: true }).ein_route, 'online');
  assert.equal(assessSelfService(company, 'self_formation', 'WY', formationAnswers).eligible, false);
  assert.equal(assessSelfService({ ...company, country: 'KR' }, 'self_formation', 'DE', formationAnswers).eligible, false);
  assert.equal(assessSelfService(company, 'self_formation', 'DE', { ...formationAnswers, registered_agent: false }).eligible, false);
  const overseas = { ...formationAnswers, operator_abroad: true, residence_reviewed: true };
  assert.equal(assessSelfService(company, 'self_formation', 'DE', overseas).eligible, true, 'overseas operation does not require US residence or SSN');
  assert.equal(assessSelfService(company, 'self_formation', 'DE', { ...overseas, residence_reviewed: false }).eligible, false);
  assert.equal(assessSelfService(company, 'self_bookkeeping', 'cashbook', { ...accountingAnswers, operator_abroad: true }).eligible, false, 'cross-border review is explicit, not inferred');
  const foreign = assessSelfService(company, 'self_bookkeeping', 'cashbook', { ...accountingAnswers, foreign_owned: true, complex_activity: true });
  assert.equal(foreign.eligible, true, 'foreign ownership and complexity do not prohibit a supplemental cashbook');
  assert.match(foreign.notices.join(' '), /보고 대상.*5472/);
  assert.match(foreign.notices.join(' '), /매출 0/);
  assert.throws(() => assessSelfService(company, 'self_formation', 'DE', { ...formationAnswers, ssn: '123' }));
});

test('DIY REST: ownership, checked selection, precise cash records, retry, reconciliation and closed-period invariants', { timeout: 120000 }, async t => {
  const { app, port, modules } = await bootApp({ port: 0 }); t.after(() => closeTestApp(app));
  const token = modules.getDataSourceToken; const ds = app.get(token());
  const owner = await createUser(app, token, { name: 'Cash owner', role: 'admin' });
  const other = await createUser(app, token, { name: 'Other admin', role: 'admin' });
  const mine = await createAccount(app, token, 'cash owner', { ownerUserId: owner.id });
  const theirs = await createAccount(app, token, 'cash other', { ownerUserId: other.id });
  const sessions = new Map([owner, other].map(u => [u.id, app.get(modules.AuthService).createSession(u.id)]));
  const call = async (path, body, { user = owner, account = mine, method = body === undefined ? 'GET' : 'POST' } = {}) => {
    const res = await fetch(`http://127.0.0.1:${port}/api/business${path}`, { method, headers: { Authorization: `Bearer ${sessions.get(user.id)}`, 'X-Account-Id': account.id, 'Content-Type': 'application/json' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    return { status: res.status, body: await res.json() };
  };
  const created = await call('/companies', { name: 'DIY LLC', jurisdiction: 'WY' }); assert.equal(created.status, 201);
  const id = created.body.id; const url = `/companies/${id}`;
  const revision = async () => (await call(url)).body.company.revision;
  const write = async (path, body) => call(`${url}${path}`, { ...body, revision: await revision() });
  const select = (provider, plan, answers) => write(`/services/${provider === 'self_formation' ? 'formation' : 'accounting'}`, { provider, plan, self_service_answers: answers });
  const otherCompany = (await call('/companies', { name: 'Other LLC' }, { user: other, account: theirs })).body;
  const month = '2020-01'; const read = () => call(`${url}/cashbook/months/${month}`);
  const entry = (overrides = {}) => ({ request_id: randomUUID(), date: `${month}-15`, kind: 'income', amount_minor: 10001, currency: 'USD', description: 'Settled sale', evidence: 'Receipt 1', ...overrides });

  await t.test('conditions cannot be bypassed and legal company edits require reconfirmation', async () => {
    assert.equal((await select('self_formation', 'WY', {})).status, 400);
    assert.equal(await revision(), 0, 'failed choices roll back the company revision');
    assert.equal((await select('self_formation', 'WY', formationAnswers)).status, 201);
    let assessment = (await call(`${url}/self-service/assess`, { provider: 'self_formation', plan: 'WY' })).body;
    assert.equal(assessment.eligible, true); assert.equal(assessment.ein_route, 'international');
    assert.equal((await call(url, { name: 'Updated DIY LLC', revision: await revision() }, { method: 'PATCH' })).status, 200);
    assessment = (await call(`${url}/self-service/assess`, { provider: 'self_formation', plan: 'WY' })).body;
    assert.equal(assessment.eligible, false); assert.equal(assessment.stale, true);
    assert.equal((await write('/cashbook/entries', entry())).status, 409);
    assert.equal((await select('self_bookkeeping', 'cashbook', accountingAnswers)).status, 201);
    assert.equal((await call(`${url}/self-service/assess`, { provider: 'self_bookkeeping', plan: 'cashbook' }, { user: other, account: theirs })).status, 403);
    assert.equal((await call(`${url}/cashbook/months/${month}`, undefined, { user: other, account: theirs })).status, 403);
  });
  let first;
  await t.test('integer USD amounts, date validity, exact retries and immutable corrections', async () => {
    for (const bad of [{ amount_minor: 0 }, { amount_minor: 0.1 }, { amount_minor: -1 }, { amount_minor: 2_000_000_001 }, { currency: 'KRW' }, { date: '2020-02-30' }, { date: '9999-01-01' }]) assert.equal((await write('/cashbook/entries', entry(bad))).status, 400);
    assert.equal((await call(`${url}/cashbook/months/2020-13`)).status, 400);
    const input = { ...entry(), revision: await revision() };
    first = (await call(`${url}/cashbook/entries`, input)).body;
    assert.ok(first.id); assert.equal(first.request_payload, undefined);
    assert.equal((await call(`${url}/cashbook/entries`, input)).body.id, first.id);
    assert.equal((await call(`${url}/cashbook/entries`, { ...input, amount_minor: 2 })).status, 409);
    assert.equal((await call(`${url}/cashbook/entries`, { ...entry(), revision: input.revision })).status, 409);
    await write('/cashbook/entries', entry({ kind: 'capital_in', amount_minor: 5000 }));
    await write('/cashbook/entries', entry({ kind: 'expense', amount_minor: 2001 }));
    const erroneous = (await write('/cashbook/entries', entry({ kind: 'transfer_out', amount_minor: 1000 }))).body;
    assert.equal((await write(`/cashbook/entries/${erroneous.id}/void`, { reason: '' })).status, 400);
    assert.equal((await write(`/cashbook/entries/${erroneous.id}/void`, { reason: 'Duplicate entry' })).status, 201);
    const state = (await read()).body;
    assert.deepEqual(state.summary, { inflow_minor: 15001, outflow_minor: 2001, net_minor: 13000, operating_in_minor: 10001, operating_out_minor: 2001, active_count: 3, unreconciled_count: 3 });
    assert.equal(state.entries.length, 4, 'voids remain available for audit/export');
    assert.equal((await write(`/cashbook/entries/${erroneous.id}/reconcile`, { evidence: 'x', reconciled: true })).status, 409);
    assert.equal((await call(`/companies/${otherCompany.id}/cashbook/entries/${first.id}/void`, { revision: 0, reason: 'stolen' }, { user: other, account: theirs })).status, 409, 'other company cannot use cashbook until selected');
    const otherSelection = await call(`/companies/${otherCompany.id}/services/accounting`, { revision: 0, provider: 'self_bookkeeping', plan: 'cashbook', self_service_answers: accountingAnswers }, { user: other, account: theirs });
    assert.equal(otherSelection.status, 201);
    assert.equal((await call(`/companies/${otherCompany.id}/cashbook/entries/${first.id}/void`, { revision: otherSelection.body.revision, reason: 'stolen' }, { user: other, account: theirs })).status, 404, 'even configured companies cannot reference another company entry');
    assert.equal((await write(`/cashbook/entries/${randomUUID()}/reconcile`, { evidence: 'x', reconciled: true })).status, 404);
  });
  await t.test('bank evidence, complete statement and closing balance gate the monthly lock', async () => {
    const close = { opening_minor: 1000, closing_minor: 14000, statement_reference: '2020-01 bank PDF', confirm_complete: true };
    assert.equal((await write(`/cashbook/months/${month}/close`, close)).status, 409);
    assert.equal((await write(`/cashbook/entries/${first.id}/reconcile`, { evidence: '', reconciled: true })).status, 400);
    for (const row of (await read()).body.entries.filter(e => !e.voided)) assert.equal((await write(`/cashbook/entries/${row.id}/reconcile`, { evidence: row.evidence, reconciled: true })).status, 201);
    assert.equal((await write(`/cashbook/months/${month}/close`, { ...close, confirm_complete: false })).status, 400);
    assert.equal((await write(`/cashbook/months/${month}/close`, { ...close, closing_minor: 14001 })).status, 409);
    assert.equal((await write(`/cashbook/months/${new Date().toISOString().slice(0, 7)}/close`, close)).status, 400);
    assert.equal((await write(`/cashbook/months/${month}/close`, close)).status, 201);
    assert.equal((await write('/cashbook/entries', entry())).status, 409);
    assert.equal((await write(`/cashbook/entries/${first.id}/void`, { reason: 'Correction' })).status, 409);
    assert.equal((await write(`/cashbook/entries/${first.id}/reconcile`, { evidence: 'Changed', reconciled: false })).status, 409);
    assert.equal((await write('/cashbook/months/2020-02/close', { ...close, opening_minor: 0, closing_minor: 0 })).status, 409, 'adjacent balances must be continuous');
    assert.equal((await write('/cashbook/months/2020-02/close', { ...close, opening_minor: 14000, closing_minor: 14000 })).status, 201);
    assert.equal((await write(`/cashbook/months/${month}/reopen`, { reason: 'Correction' })).status, 409, 'later closed periods protect prior history');
    assert.equal((await write('/cashbook/entries', entry({ date: '2019-12-01' }))).status, 409);
    assert.equal((await write('/cashbook/months/2020-02/reopen', { reason: 'Review earlier month' })).status, 201);
    assert.equal((await write(`/cashbook/months/${month}/reopen`, { reason: 'Correct duplicate' })).status, 201);
    assert.equal((await write(`/cashbook/entries/${first.id}/void`, { reason: 'Correct duplicate' })).status, 201);
    assert.equal((await read()).body.summary.net_minor, 2999);
  });
  await t.test('concurrent writes use company CAS and provider changes preserve export', async () => {
    const rev = await revision();
    const results = await Promise.all([call(`${url}/cashbook/entries`, { ...entry(), revision: rev }), call(`${url}/cashbook/entries`, { ...entry(), revision: rev })]);
    assert.deepEqual(results.map(r => r.status).sort(), [201, 409]);
    const catalog = (await call('/connectors')).body;
    assert.equal(catalog.filter(c => c.mode === 'manual').length, 2);
    const xero = catalog.find(c => c.id === 'xero');
    assert.equal((await select('xero', xero.offering.pricing.plans[0].id)).status, 201);
    assert.equal((await read()).status, 200);
    assert.equal((await write('/cashbook/entries', entry())).status, 409);
    assert.equal(await ds.getRepository('Ticket').countBy({ account_id: mine.id }), 0);
    assert.ok((await ds.getRepository('BusinessEvent').findBy({ company_id: id, kind: 'cashbook' })).some(e => e.message.includes('마감 재개')));
  });
});
